import React, { useState } from 'react';
import { FileCode, Copy, Check, ExternalLink, X, ShieldAlert } from 'lucide-react';

interface RobotsTxtModalProps {
  isOpen: boolean;
  onClose: () => void;
}

export const RobotsTxtModal: React.FC<RobotsTxtModalProps> = ({ isOpen, onClose }) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const robotsContent = `# Robots.txt generated by PulseNews Security Engine
# Optimized for Ultra Fast Loading, Server Protection & AI Scraper Defense
# Updated: ${new Date().toISOString().split('T')[0]}

User-agent: *
Allow: /
Disallow: /api/
Disallow: /admin
Disallow: /private/

# Strict Disallow Rules for AI Scrapers & Data Harvesters
User-agent: ByteSpider
Disallow: /

User-agent: GPTBot
Disallow: /

User-agent: CCBot
Disallow: /

User-agent: ClaudeBot
Disallow: /

User-agent: PerplexityBot
Disallow: /

User-agent: Google-Extended
Disallow: /

User-agent: Amazonbot
Disallow: /

User-agent: FacebookBot
Disallow: /

# Crawl-delay recommendation to prevent server overload
Crawl-delay: 10
Sitemap: ${window.location.origin}/sitemap.xml`;

  const handleCopy = () => {
    navigator.clipboard.writeText(robotsContent);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-950/80 backdrop-blur-md flex items-center justify-center p-4 overflow-y-auto font-sans">
      <div className="bg-white dark:bg-slate-900 w-full max-w-xl rounded-2xl border border-slate-200 dark:border-slate-800 shadow-2xl overflow-hidden my-auto">
        <div className="px-6 py-4 bg-slate-900 text-white flex items-center justify-between border-b border-slate-800">
          <div className="flex items-center gap-2">
            <FileCode className="w-5 h-5 text-indigo-400" />
            <h3 className="font-bold text-base">AI Scraper Blocking /robots.txt Manager</h3>
          </div>
          <button onClick={onClose} className="p-1 rounded text-slate-400 hover:text-white">
            <X className="w-5 h-5" />
          </button>
        </div>

        <div className="p-6 space-y-4">
          <div className="p-3 rounded-xl bg-indigo-50 dark:bg-indigo-950/50 border border-indigo-200 dark:border-indigo-800 text-xs text-indigo-800 dark:text-indigo-200 flex items-start gap-2">
            <ShieldAlert className="w-4 h-4 text-indigo-500 shrink-0 mt-0.5" />
            <span>
              This <strong>robots.txt</strong> file is automatically served by the Express gateway to enforce disallow rules for AI crawlers like ByteSpider, GPTBot, and ClaudeBot to prevent server overload.
            </span>
          </div>

          <div className="relative rounded-xl overflow-hidden border border-slate-200 dark:border-slate-800 bg-slate-950 text-emerald-400 p-4 font-mono text-xs leading-relaxed max-h-72 overflow-y-auto">
            <pre>{robotsContent}</pre>
          </div>

          <div className="flex items-center justify-between gap-3 pt-2">
            <a
              href="/robots.txt"
              target="_blank"
              rel="noopener noreferrer"
              className="text-xs text-indigo-600 dark:text-indigo-400 font-semibold hover:underline flex items-center gap-1"
            >
              <ExternalLink className="w-3.5 h-3.5" />
              <span>Inspect live /robots.txt on Server</span>
            </a>

            <button
              onClick={handleCopy}
              className="px-4 py-2 bg-indigo-600 hover:bg-indigo-500 text-white text-xs font-medium rounded-xl flex items-center gap-1.5 shadow transition"
            >
              {copied ? <Check className="w-4 h-4" /> : <Copy className="w-4 h-4" />}
              <span>{copied ? 'Copied' : 'Copy Robots.txt'}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
